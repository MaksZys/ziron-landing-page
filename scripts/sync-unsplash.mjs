import { mkdir, writeFile } from 'node:fs/promises';

const ACCESS_KEY = process.env.UNSPLASH_ACCESS_KEY;
const OUTPUT_PATH = new URL('../src/content/portfolio.generated.ts', import.meta.url);
const SEARCHES = [
  { category: 'Automotive film', query: 'performance car driving motion', title: 'Velocity, framed' },
  { category: 'Motorcycle stories', query: 'motorcycle workshop cinematic', title: 'Built by hand' },
  { category: 'Industrial image', query: 'industrial machinery cinematic', title: 'Precision at scale' },
];
const PROJECT_SEARCHES = [
  'snow plow truck night',
  'heavy construction loader',
  'semi truck road',
  'sports car detail',
  'tractor field',
  'off road pickup dust',
  'luxury sports car road',
  'agriculture tractor snow',
];

if (!ACCESS_KEY) {
  throw new Error('UNSPLASH_ACCESS_KEY is required to refresh portfolio media.');
}

function isUnsplashPhoto(value) {
  return (
    typeof value === 'object' &&
    value !== null &&
    typeof value.id === 'string' &&
    typeof value.alt_description === 'string' &&
    typeof value.urls?.raw === 'string' &&
    typeof value.user?.name === 'string' &&
    typeof value.user?.links?.html === 'string' &&
    typeof value.links?.html === 'string'
  );
}

async function searchPhoto(search) {
  const endpoint = new URL('https://api.unsplash.com/search/photos');
  endpoint.searchParams.set('query', search.query);
  endpoint.searchParams.set('orientation', 'landscape');
  endpoint.searchParams.set('content_filter', 'high');
  endpoint.searchParams.set('per_page', '1');

  const response = await fetch(endpoint, {
    headers: {
      Authorization: `Client-ID ${ACCESS_KEY}`,
      'Accept-Version': 'v1',
    },
  });

  if (!response.ok) {
    throw new Error(`Unsplash search failed for "${search.query}" with status ${response.status}.`);
  }

  const payload = await response.json();
  const photo = payload?.results?.[0];

  if (!isUnsplashPhoto(photo)) {
    throw new Error(`Unsplash returned no usable photo for "${search.query}".`);
  }

  const imageUrl = new URL(photo.urls.raw);
  imageUrl.searchParams.set('auto', 'format');
  imageUrl.searchParams.set('fit', 'crop');
  imageUrl.searchParams.set('q', '86');
  imageUrl.searchParams.set('w', '2400');

  const attributionParameters = '?utm_source=ziron_portfolio&utm_medium=referral';

  return {
    alt: photo.alt_description,
    category: search.category,
    id: photo.id,
    imageUrl: imageUrl.toString(),
    photographerName: photo.user.name,
    photographerProfileUrl: `${photo.user.links.html}${attributionParameters}`,
    sourceUrl: `${photo.links.html}${attributionParameters}`,
    title: search.title,
  };
}

async function searchProjectImage(query) {
  const photo = await searchPhoto({
    category: 'Maszyny w ruchu',
    query,
    title: 'Siła w ruchu',
  });

  return {
    alt: photo.alt,
    height: 1600,
    id: photo.id,
    imageUrl: photo.imageUrl,
    photographerName: photo.photographerName,
    photographerProfileUrl: photo.photographerProfileUrl,
    sourceUrl: photo.sourceUrl,
    width: 2400,
  };
}

const [slides, projectImages] = await Promise.all([
  Promise.all(SEARCHES.map(searchPhoto)),
  Promise.all(PROJECT_SEARCHES.map(searchProjectImage)),
]);
const project = {
  category: 'Film produkcyjny / Kampania 2026',
  images: projectImages,
  summary:
    'Maszyny nie pozują. Pracują. Pokazaliśmy ich siłę tam, gdzie jest najbardziej prawdziwa — w pyle, śniegu, deszczu i pełnym tempie.',
  title: 'Siła w ruchu',
};
const source = `// Generated by npm run content:unsplash. Do not edit by hand.\nimport type { PortfolioProject, PortfolioSlide } from './portfolio';\n\nexport const PORTFOLIO_SLIDES = ${JSON.stringify(slides, null, 2)} satisfies PortfolioSlide[];\n\nexport const FEATURED_PROJECT = ${JSON.stringify(project, null, 2)} satisfies PortfolioProject;\n`;

await mkdir(new URL('../src/content/', import.meta.url), { recursive: true });
await writeFile(OUTPUT_PATH, source, 'utf8');

console.log(`Saved ${slides.length} Unsplash photos without exposing credentials.`);
